// Bundles the sign-in Lambda into one ES module and embeds it as a string, so the Pulumi
// component can deploy it without depending on file paths, which bundlers (e.g. SST's) move.
import { mkdirSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const result = await build({
  entryPoints: [new URL('../src/lambda/handler.ts', import.meta.url).pathname],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  write: false,
  legalComments: 'none',
});

const generated = new URL('../src/generated/', import.meta.url);
mkdirSync(generated, { recursive: true });
writeFileSync(
  new URL('lambda-code.ts', generated),
  `// Generated by scripts/generate-lambda-code.ts. Do not edit.\nexport const lambdaCode: string = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
